export function convertToDialect(text: string, dialectId: string): { result: string; annotations: Array<{ original: string; converted: string; pronunciation: string }> } {
  const dialect = dialects.find(d => d.id === dialectId)
  if (!dialect) return { result: text, annotations: [] }

  const annotations: Array<{ original: string; converted: string; pronunciation: string }> = []
  let result = text

  const sortedKeys = Object.keys(dialect.wordMap).sort((a, b) => b.length - a.length)

  for (const mandarinWord of sortedKeys) {
    const wordData = dialect.wordMap[mandarinWord]
    if (result.includes(mandarinWord)) {
      const regex = new RegExp(mandarinWord, 'g')
      result = result.replace(regex, wordData.dialect)
      annotations.push({
        original: mandarinWord,
        converted: wordData.dialect,
        pronunciation: wordData.pronunciation
      })
    }
  }

  return { result, annotations: [...new Map(annotations.map(a => [a.original, a])).values()] }
}

export function getDialectById(id: string): Dialect | undefined {
  return dialects.find(d => d.id === id)
}
